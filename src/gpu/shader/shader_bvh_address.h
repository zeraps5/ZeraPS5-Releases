#ifndef PS5C_SHADER_BVH_ADDRESS_H
#define PS5C_SHADER_BVH_ADDRESS_H
#define SH_BVH_REQUEST_SLOTS 8192u
#define SH_BVH_PAGE_SHIFT 16u
#define SH_BVH_PAGE_BYTES (1u << SH_BVH_PAGE_SHIFT)
#define SH_BVH_READ_MASK_WORDS (SH_BVH_PAGE_BYTES / 64u / 32u)
#define SH_BVH_READ_MASK_BASE (4u + SH_BVH_REQUEST_SLOTS)
#define SH_BVH_PAGED_HEADER (SH_BVH_READ_MASK_BASE + SH_BVH_REQUEST_SLOTS * SH_BVH_READ_MASK_WORDS)
#endif
