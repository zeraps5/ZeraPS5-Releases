/* Half-pixel scale units: 2 = 1x, 3 = compact 1.5x, 4 = the original 2x.
 * Rasterize with integer edges to keep the smaller font sharp. */
static inline void vk_overlay_size_scaled(uint32_t cols, uint32_t lines, uint32_t scale_x2,
                                          uint32_t *w, uint32_t *h) {
    *w = cols * (3u * scale_x2) + 2 * VK_OVERLAY_PAD;
    *h = lines * ((9u * scale_x2 + 1) / 2) + 2 * VK_OVERLAY_PAD;
}

static inline void vk_overlay_size(uint32_t cols, uint32_t lines, uint32_t *w, uint32_t *h) {
    vk_overlay_size_scaled(cols, lines, 2 * VK_OVERLAY_SCALE, w, h);
}

/* Draws the lines into a w x h image of 32-bit texels; bgra: byte order B, G, R, A */
static inline void vk_overlay_render_scaled(uint8_t *px, uint32_t w, uint32_t h, const char *const *lines,
                                            uint32_t n, bool bgra, uint32_t scale_x2) {
    if (!px || !w || !h || !scale_x2) return;
    const uint8_t bg[3] = {16, 16, 24}, fg[3] = {120, 255, 160}; /* R, G, B */
    for (uint32_t i = 0; i < w * h; i++) {
        px[4 * i + 0] = bgra ? bg[2] : bg[0];
        px[4 * i + 1] = bg[1];
        px[4 * i + 2] = bgra ? bg[0] : bg[2];
        px[4 * i + 3] = 255;
    }
    uint32_t cell_w = 3u * scale_x2, cell_h = (9u * scale_x2 + 1) / 2;
    for (uint32_t l = 0; l < n && VK_OVERLAY_PAD + l * cell_h < h; l++) {
        for (uint32_t k = 0; lines[l][k] && VK_OVERLAY_PAD + k * cell_w < w; k++) {
            const uint8_t *g = vk_overlay_glyph(lines[l][k]);
            if (!g) continue;
            uint32_t x0 = VK_OVERLAY_PAD + k * cell_w, y0 = VK_OVERLAY_PAD + l * cell_h;
            for (uint32_t row = 0; row < 7; row++)
                for (uint32_t col = 0; col < 5; col++) {
                    if (!((g[row] >> (4 - col)) & 1)) continue;
                    for (uint32_t y = y0 + row * scale_x2 / 2; y < y0 + (row + 1) * scale_x2 / 2 && y < h; y++)
                        for (uint32_t x = x0 + col * scale_x2 / 2; x < x0 + (col + 1) * scale_x2 / 2 && x < w; x++) {
                            uint8_t *p = px + 4 * ((size_t)y * w + x);
                            p[0] = bgra ? fg[2] : fg[0];
                            p[1] = fg[1];
                            p[2] = bgra ? fg[0] : fg[2];
                        }
                }
        }
    }
}

static inline void vk_overlay_render(uint8_t *px, uint32_t w, uint32_t h, const char *const *lines, uint32_t n, bool bgra) {
    vk_overlay_render_scaled(px, w, h, lines, n, bgra, 2 * VK_OVERLAY_SCALE);
}

