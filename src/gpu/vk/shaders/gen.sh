#!/bin/bash
# Regenerates vk_fsr1_spv.h from the GLSL here (needs glslangValidator; the build does not).
cd "$(dirname "$0")" || exit 1
out=../vk_fsr1_spv.h
{
  echo "/* Generated by src/gpu/vk/shaders/gen.sh from fsr1_easu.comp and fsr1_rcas.comp: do not edit. */"
  echo "#pragma once"
  echo "#include <stdint.h>"
} > $out
for s in easu rcas; do
  glslangValidator -V --target-env vulkan1.1 --vn fsr1_${s}_spv -o /tmp/fsr1_$s.h fsr1_$s.comp || exit 1
  grep -v -E '^[[:space:]]*(#|//)|^[[:space:]]*$' /tmp/fsr1_$s.h | sed 's/^const uint32_t/static const uint32_t/' >> $out
done
