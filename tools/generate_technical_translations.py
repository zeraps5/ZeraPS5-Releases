"""Compile checked-in technical translations. Offline; no model is distributed."""
from pathlib import Path
import ast,json,re
root=Path(__file__).resolve().parents[1]
languages=['pt-BR','pt-PT','en','es','fr','de','it','ja','ko','zh-CN','zh-TW','ar','fa','ru','uk']
fmt=re.compile(r'%(?:[-+ #0]*)(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hlLzjt])?[diuoxXfFeEgGaAcsp%]')
items=json.loads((root/'frontends/launcher/technical_translations.json').read_text(encoding='utf8'))
seen=set()
for item in items:
    assert item['source'] not in seen or item['kind']=='doc',item['source']
    seen.add(item['source'])
    assert set(item['text'])==set(languages),item['source']
    assert all(item['text'].values()),item['source']
    assert all(fmt.findall(v)==fmt.findall(item['source'])for v in item['text'].values()),item['source']

def ctext(s):
    # JSON escapes control chars with universal escapes, which are not valid C
    # for low controls. Fixed-width octal is safe before arbitrary digits.
    text=json.dumps(s,ensure_ascii=False)
    return re.sub(r'\\u00([0-1][0-9a-f])',lambda m:'\\%03o'%int(m[1],16),text)

logs={x['source']:x['text']for x in items if x['kind']=='log'}
pri={'u64':'llu','d64':'lld','i64':'lli','x64':'llx','X64':'llX','uPTR':'llu','xPTR':'llx','dPTR':'lld','u32':'u','x32':'x','d32':'d'}
pattern=re.compile(r'(?:LOG_[TDIWE]\s*\(\s*[A-Z_]+|log_emit\s*\(\s*LOG_CAT_[A-Z_]+\s*,\s*LOG_LVL_[A-Z_]+)\s*,\s*((?:"(?:[^"\\]|\\.)*"|PRI[A-Za-z0-9_]+)(?:\s*(?:"(?:[^"\\]|\\.)*"|PRI[A-Za-z0-9_]+))*)')
calls=0;value_masks={}
def arguments_after(text,pos):
    while pos<len(text) and text[pos].isspace():pos+=1
    if pos==len(text) or text[pos]!=',':return []
    pos+=1;start=pos;depth=1;args=[]
    while pos<len(text):
        ch=text[pos]
        if ch in '\"\'':
            quote=ch;pos+=1
            while pos<len(text):
                if text[pos]=='\\':pos+=2;continue
                if text[pos]==quote:break
                pos+=1
        elif ch=='(':depth+=1
        elif ch==')':
            depth-=1
            if not depth:args.append(text[start:pos]);return args
        elif ch==',' and depth==1:args.append(text[start:pos]);start=pos+1
        pos+=1
    raise AssertionError('Unclosed diagnostic call')
for file in [*root.glob('src/**/*.c'),*root.glob('src/**/*.h'),*root.glob('frontends/cli/*.c')]:
    contents=file.read_text(encoding='utf8')
    for match in pattern.finditer(contents):
        parts=re.findall(r'"(?:[^"\\]|\\.)*"|PRI[A-Za-z0-9_]+',match[1])
        source=''.join(pri[x[3:]]if x.startswith('PRI')else ast.literal_eval(x)for x in parts)
        assert source in logs,f'Untranslated diagnostic: {file.relative_to(root)}: {source}'
        # Only explicitly typed error descriptions may be localized as values.
        # A game title or filename that happens to equal "busy" stays intact.
        args=arguments_after(contents,match.end());arg=0;field=0;mask=0
        for spec in fmt.findall(source):
            if spec=='%%':continue
            arg+=spec.count('*')
            if arg<len(args) and re.search(r'\bps5c_err_str\s*\(',args[arg]):mask|=1<<field
            field+=1;arg+=1
        value_masks.setdefault(source,set()).add(mask)
        calls+=1
lines=['/* SPDX-License-Identifier: GPL-2.0-or-later */','/* Generated by tools/generate_technical_translations.py. */',
       'typedef struct ui_log_message { const char *source; const char *text[15]; uint64_t value_mask; } ui_log_message;',
       'static const ui_log_message ui_log_messages[] = {']
for source,translations in sorted(logs.items(),key=lambda kv:kv[0].encode('utf8')):
    masks=value_masks.get(source,{0});mask=next(iter(masks))if len(masks)==1 else 0
    lines.append('    {'+ctext(source)+', {'+', '.join(ctext(translations[tag])for tag in languages)+'}, UINT64_C('+str(mask)+')},')
lines.append('};\n')
(root/'frontends/launcher/log_translations.inc').write_text('\n'.join(lines),encoding='utf8',newline='\n')

# Readable help in the selected language; licenses and credits retain their
# authoritative originals. Commands, paths and repository identifiers are data.
docs={}
for item in items:
    if item['kind']!='doc' or item['file'].endswith('CREDITS.txt'):continue
    docs.setdefault(item['file'],{})[item['line']]=item['text']
for tag in languages:
    blocks=[]
    for file,translations in sorted(docs.items()):
        original=(root/file).read_text(encoding='utf-8-sig').splitlines()
        lines=[]
        for n,line in enumerate(original):
            if (not line.strip() or line.startswith(('powershell ','cmake ','ctest ','https://')) or
                re.fullmatch(r'\s*[\w.-]+\.(?:sprx|dll|exe|json|txt|zip)\s*',line) or
                (file.endswith('IDIOMAS.txt') and line.startswith('- '))):lines.append(line)
            else:lines.append(translations[n][tag])
        blocks.extend(['\n'+file+'\n'+'='*40,*lines])
    (root/f'dist/docs/HELP-{tag}.txt').write_text('\n'.join(blocks)+'\n',encoding='utf8',newline='\n')

# Self-contained installer: recovery still works after an interrupted update,
# without depending on a separately installed language file.
script=root/'tools/apply-update.ps1'
text=script.read_text(encoding='utf-8-sig')
dictionary={x['source']:x['text']for x in items if x['kind']=='installer'}
begin='# BEGIN GENERATED UPDATE TRANSLATIONS';end='# END GENERATED UPDATE TRANSLATIONS'
block=begin+"\n$script:UpdateMessages = @'\n"+json.dumps(dictionary,ensure_ascii=False,separators=(',',':'))+"\n'@ | ConvertFrom-Json\n"+end
assert begin in text and end in text
text=text[:text.index(begin)]+block+text[text.index(end)+len(end):]
script.write_text(text,encoding='utf-8-sig',newline='\n')
print(f'{len(logs)} technical messages, {calls} log calls, {len(docs)} help documents and {len(dictionary)} update messages in 15 languages; placeholders checked')
