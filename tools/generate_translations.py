"""Regenerate compiled UTF-16 launcher messages. No network or external packages."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
rows=[];seen=set();table={}
pattern=re.compile(r'%(?:[-+ #0]*\d*(?:\.\d+)?)(?:hh|ll|[hlLzjt])?[diuoxXfFeEgGaAcsp%]')
for line in (root/'frontends/launcher/translations.tsv').read_text(encoding='utf8').splitlines():
    if not line or line.startswith('#'):continue
    cells=[v.replace('\\n','\n').replace('\\r','\r')for v in line.split('|')]
    assert len(cells)==14,(len(cells),cells[0])
    assert all(cells),cells[0]
    assert cells[0]not in seen,cells[0];seen.add(cells[0])
    assert all(pattern.findall(v)==pattern.findall(cells[0]) for v in cells),cells[0]
    # PT-PT is independently selectable; shared orthography falls back to PT-BR.
    pt=cells[0].replace('arquivo','ficheiro').replace('Arquivos','Ficheiros').replace('Placa de vídeo:','Placa gráfica:')
    values=[cells[0],pt,*cells[1:]]
    table[cells[0]]=values
    rows.append('    {'+', '.join('L'+json.dumps(v,ensure_ascii=False)for v in values)+'},')
extra=root/'frontends/launcher/translations_extra.json'
if extra.exists():
    languages=['pt-BR','pt-PT','en','es','fr','de','it','ja','ko','zh-CN','zh-TW','ar','fa','ru','uk']
    for source,translations in json.loads(extra.read_text(encoding='utf8')).items():
        assert source not in seen,source
        values=[translations[tag]for tag in languages]
        assert values[0]==source and all(values),source
        assert all(pattern.findall(v)==pattern.findall(source)for v in values),source
        seen.add(source);table[source]=values
        rows.append('    {'+', '.join('L'+json.dumps(v,ensure_ascii=False)for v in values)+'},')
for source,target in json.loads((root/'frontends/launcher/translation_aliases.json').read_text(encoding='utf8')).items():
    if source in seen:continue
    assert target in table,source
    values=[source,*table[target][1:]]
    assert all(pattern.findall(v)==pattern.findall(source)for v in values),source
    rows.append('    {'+', '.join('L'+json.dumps(v,ensure_ascii=False)for v in values)+'},')
out='/* SPDX-License-Identifier: GPL-2.0-or-later */\n/* Generated by tools/generate_translations.py. */\nstatic const wchar_t *const ui_messages[][15] = {\n'+'\n'.join(rows)+'\n};\n'
(root/'frontends/launcher/translations.inc').write_text(out,encoding='utf8',newline='\n')
print(len(rows),'messages in 15 interface languages; format arguments verified')
